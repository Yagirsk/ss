LEFT JOIN Формирование f ON t.ID_Формирования = f.ID
LEFT JOIN Характеристика_техники ht ON tt.ID = ht.ID_Техники
LEFT JOIN Справочник_характеристик_техники sht ON ht.ID_Характеристики = sht.ID
GROUP BY t.ID, tt.Название, ct.Категория, t.Серийный_номер, f.Название;




CREATE OR REPLACE VIEW vw_Вооружение AS
SELECT
    wt.Название AS Название_вооружения,
    cw.Категория AS Категория_вооружения,
    w.Инвентарный_номер,
    f.Название AS Формирование,
    GROUP_CONCAT(CONCAT(shw.Характеристика, ': ', hw.Значение_характеристики) ORDER BY shw.Характеристика SEPARATOR ', ') AS Характеристики
FROM Вооружение w
JOIN Вооружение_тип wt ON w.ID_вооружения = wt.ID
JOIN Справочник_категорий_вооружения cw ON wt.ID_категории = cw.ID
LEFT JOIN Формирование f ON w.ID_Формирования = f.ID
LEFT JOIN Характеристика_вооружения hw ON wt.ID = hw.ID_Вооружения
LEFT JOIN Справочник_характеристик_вооружения shw ON hw.ID_Характеристики = shw.ID
GROUP BY w.ID, w.Инвентарный_номер, wt.Название, cw.Категория, f.Название;


