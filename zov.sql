CREATE TRIGGER trg_check_building_assignment
BEFORE INSERT ON Здание_под_дислокацию_формирований
FOR EACH ROW
BEGIN
    DECLARE формирование_в_здании INT;
    DECLARE владелец_формирования INT;
    DECLARE тип_дислокации VARCHAR(50);
    DECLARE тип_владельца VARCHAR(50);
    DECLARE is_valid BOOL DEFAULT FALSE;

    SELECT ID_Формирования INTO владелец_формирования
    FROM Здание
    WHERE ID = NEW.ID_Здания;

    SELECT stf.Тип INTO тип_дислокации
    FROM Формирование f
    JOIN Справочник_типов_формирований stf ON f.ID_Типа = stf.ID
    WHERE f.ID = NEW.ID_Формирования;

    IF тип_дислокации NOT IN ('Рота', 'Взвод', 'Отделение') THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'Допускается размещение только Роты, Взвода или Отделения';
    END IF;

    WITH RECURSIVE Иерархия AS (
        SELECT ID FROM Формирование WHERE ID = владелец_формирования
        UNION ALL
        SELECT f.ID
        FROM Формирование f
        JOIN Иерархия h ON f.Вышестоящее_формирование = h.ID
    )
    SELECT TRUE INTO is_valid
    FROM Иерархия
    WHERE ID = NEW.ID_Формирования
    LIMIT 1;

    IF NOT is_valid THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'Формирование не подчинено владельцу здания';
    END IF;
END;
//

