CREATE OR REPLACE VIEW vw_Военнослужащие_расширенно AS
SELECT
    v.ID,
    v.ФИО,
    z.Звание,
    f.Название AS Формирование,
    n.ФИО AS Начальник,

    (
        SELECT GROUP_CONCAT(s.Специальность SEPARATOR ', ')
        FROM Специальность_военнослужащего sv
        JOIN Справочник_специальностей s ON sv.ID_Специальности = s.ID
        WHERE sv.ID_Военнослужащего = v.ID
    ) AS Специальности,

    (
        SELECT GROUP_CONCAT(CONCAT(hc.Характеристика, ': ', hv.Значение_характеристики) SEPARATOR ', ')
        FROM Характеристика_военнослужащего hv
        JOIN Справочник_характеристик_военнослужащего hc ON hv.ID_Характеристики = hc.ID
        WHERE hv.ID_Военнослужащего = v.ID
    ) AS Характеристики

FROM Военнослужащий v
LEFT JOIN Справочник_званий z ON v.ID_Звания = z.ID
LEFT JOIN Формирование f ON v.ID_Формирования = f.ID
LEFT JOIN Военнослужащий n ON v.Начальник = n.ID;




CREATE OR REPLACE VIEW vw_Формирования_расширенно AS
SELECT
    f.ID,
    f.Название AS Формирование,
    tf.Тип AS Тип_формирования,

    c.ФИО AS Командир,
    z.Звание AS Звание_командира,

    f2.Название AS Вышестоящее_формирование

FROM Формирование f
LEFT JOIN Справочник_типов_формирований tf ON f.ID_Типа = tf.ID
LEFT JOIN Военнослужащий c ON f.ID_командира = c.ID
LEFT JOIN Справочник_званий z ON c.ID_Звания = z.ID
LEFT JOIN Формирование f2 ON f.Вышестоящее_формирование = f2.ID;




CREATE OR REPLACE VIEW vw_Здания_с_дислокацией AS
SELECT
    z.ID,
    z.Название AS Здание,
    sz.Здание AS Тип_здания,
    f.Название AS Владельное_формирование,
    GROUP_CONCAT(fd.Название ORDER BY fd.Название SEPARATOR ', ') AS Дислоцируемые_формирования

FROM Здание z
LEFT JOIN Справочник_зданий sz ON z.ID_Типа = sz.ID
LEFT JOIN Формирование f ON z.ID_Формирования = f.ID
LEFT JOIN Здание_под_дислокацию_формирований zfd ON z.ID = zfd.ID_Здания
LEFT JOIN Формирование fd ON zfd.ID_Формирования = fd.ID

GROUP BY z.ID, z.Название, sz.Здание, f.Название;




CREATE OR REPLACE VIEW vw_Места_дислокации_с_частями AS
SELECT
    md.ID,
    md.Название AS Место_дислокации,
    md.Регион,
    std.Тип_места_дилокации AS Тип,
    GROUP_CONCAT(f.Название ORDER BY f.Название SEPARATOR ', ') AS Дислоцированные_части

FROM Место_дислокации md
LEFT JOIN Справочник_типов_мест_дислокации std ON md.ID_типа = std.ID
LEFT JOIN Дислокация_формирования df ON md.ID = df.ID_Места_дислокации
LEFT JOIN Формирование f ON df.ID_Формирования = f.ID AND f.ID_Типа = (
    SELECT ID FROM Справочник_типов_формирований WHERE Тип = 'Воинская часть' LIMIT 1
)

GROUP BY md.ID, md.Название, md.Регион, std.Тип_места_дилокации;




